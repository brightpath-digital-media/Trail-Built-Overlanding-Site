#!/usr/bin/env node
/**
 * Covers the newsletter ARCHIVE ISSUE (continuity plan, Step 6) in
 * scripts/prepare-weekly-newsletter.mjs.
 *
 * Every case runs the real script against a synthetic articles/, newsletters/ and
 * index.html fixture. Nothing touches the network and nothing is committed.
 *
 *   A. flag OFF is unchanged: the pre-existing outcomes (fresh issue, stall failure,
 *      stale no-op, already staged, future date, test mode) are compared byte for
 *      byte (stdout, stderr, exit code, staged files, result file, GITHUB_OUTPUT)
 *      with scripts/fixtures/newsletter-archive/golden-flag-off.json, which was
 *      generated by the pre-change script. Any ALLOW_ARCHIVE_ISSUE value other
 *      than exactly "true" must match the same golden.
 *   B. flag ON + stale stages `<date>-archive-<slug>` with a "From the archive:"
 *      subject and content built only from the Editor's Pick card and meta.
 *   C. each guard blocks with its own named reason, and the outcome then falls back
 *      to exactly today's behavior (CONTENT_STALLED failure, or the stale no-op):
 *        archive-14-day-limit, archive-consecutive-week, editors-pick-already-issued,
 *        editors-pick-is-last-sent, plus the pick-quality reasons.
 *   D. the rendered archive HTML has no '$', 'price', 'offers' or amazon.com link.
 *
 * Regenerate the golden only from the pre-change script:
 *   node scripts/test-newsletter-archive-issue.mjs --write-golden <path-to-old-script-inside-scripts/>
 */

import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultScript = path.join(root, "scripts", "prepare-weekly-newsletter.mjs");
const goldenPath = path.join(root, "scripts", "fixtures", "newsletter-archive", "golden-flag-off.json");
const workspace = fs.mkdtempSync(path.join(os.tmpdir(), "newsletter-archive-"));
const TODAY = "2026-11-03"; // a Tuesday
const DOMAIN = "https://trailbuiltoverland.com";

const DESCRIPTION = "Ground tent or rooftop tent for overlanding? Compare setup, roof load, space and weather trade-offs.";

function articlePage({ slug, title, publishDate, description = DESCRIPTION, ogTitleOnly = false }) {
  const url = `${DOMAIN}/articles/${slug}.html`;
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Article",
    ...(ogTitleOnly ? {} : { headline: title }),
    description,
    image: { "@type": "ImageObject", url: "https://images.example.com/hero.jpg" },
    datePublished: publishDate,
    url,
  };
  return `<!doctype html>
<html lang="en"><head>
<link rel="canonical" href="${url}" />
<meta name="description" content="${description}" />
<meta property="og:title" content="${title}" />
<meta property="og:image" content="https://images.example.com/hero.jpg" />
<script type="application/ld+json">${JSON.stringify(jsonLd)}</script>
</head><body><p>A deliberately long enough body paragraph so the excerpt builder has a second sentence to work with here.</p></body></html>
`;
}

function indexPage({ slug, marker = null, image = "assets/product-images/ground-tent.jpg", alt = "A gray ground tent beside an SUV", noCard = false }) {
  const markerLine = marker ? `<!-- editors-pick: week=${marker.week} slug=${marker.slug} -->\n` : "";
  const card = noCard
    ? ""
    : `${markerLine}<div class="card card-featured">
<div class="card-img"><img alt="${alt}" decoding="async" loading="lazy" src="${image}"/></div>
<div class="card-body">
<h3><a href="articles/${slug}.html">Some card title</a></h3>
<p>Card summary text that is not used.</p>
<div class="card-footer"><a class="read-link" href="articles/${slug}.html">Read Full Guide →</a></div>
</div>
</div>
`;
  return `<!doctype html><html><body><section id="featured">\n<h2>Editor's Pick</h2>\n${card}</section>\n<!-- ===== LATEST REVIEWS ===== -->\n<section id="reviews"><div class="card"><a href="articles/other-latest.html">x</a></div></section></body></html>\n`;
}

let caseIndex = 0;
function setup({ articles, preStage = [], index = null, imageFile = "assets/product-images/ground-tent.jpg" }) {
  const label = `case-${++caseIndex}`;
  const dir = path.join(workspace, label);
  const articlesDir = path.join(dir, "articles");
  const outputDir = path.join(dir, "newsletters");
  const siteDir = path.join(dir, "site");
  for (const d of [articlesDir, outputDir, siteDir]) fs.mkdirSync(d, { recursive: true });
  for (const article of articles) fs.writeFileSync(path.join(articlesDir, `${article.slug}.html`), articlePage(article), "utf8");
  for (const stem of preStage) fs.writeFileSync(path.join(outputDir, `${stem}.html`), "staged earlier", "utf8");
  if (index) fs.writeFileSync(path.join(siteDir, "index.html"), indexPage(index), "utf8");
  if (imageFile) {
    fs.mkdirSync(path.join(siteDir, path.dirname(imageFile)), { recursive: true });
    fs.writeFileSync(path.join(siteDir, imageFile), "fake image bytes", "utf8");
  }
  return { label, dir, articlesDir, outputDir, siteDir };
}

function execute(ctx, { today = TODAY, env = {}, script = defaultScript } = {}) {
  const resultFile = path.join(ctx.dir, "result.json");
  const outputFile = path.join(ctx.dir, "github-output.txt");
  fs.rmSync(resultFile, { force: true });
  fs.rmSync(outputFile, { force: true });
  const run = spawnSync(process.execPath, [script], {
    cwd: root,
    encoding: "utf8",
    env: {
      ...process.env,
      NEWSLETTER_NOW: today,
      NEWSLETTER_ARTICLES_DIR: ctx.articlesDir,
      NEWSLETTER_OUTPUT_DIR: ctx.outputDir,
      NEWSLETTER_INDEX_FILE: path.join(ctx.siteDir, "index.html"),
      NEWSLETTER_RESULT_FILE: resultFile,
      NEWSLETTER_COMMIT: "false",
      NEWSLETTER_TEST_MODE: "",
      GITHUB_ACTIONS: "",
      GITHUB_OUTPUT: outputFile,
      ALLOW_ARCHIVE_ISSUE: "",
      ...env,
    },
  });
  const read = (file) => (fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null);
  const staged = fs.readdirSync(ctx.outputDir).sort();
  return {
    status: run.status,
    stdout: run.stdout,
    stderr: run.stderr,
    staged,
    files: Object.fromEntries(staged.map((name) => [name, fs.readFileSync(path.join(ctx.outputDir, name), "utf8")])),
    result: read(resultFile),
    githubOutput: read(outputFile),
  };
}

function normalise(outcome, ctx) {
  const rel = path.relative(root, ctx.dir);
  const scrub = (text) =>
    text === null
      ? null
      : text.split(ctx.dir).join("<WS>").split(rel).join("<WS>").replace(/"stagedAt": "[^"]+"/g, '"stagedAt": "<STAGED_AT>"');
  return {
    status: outcome.status,
    stdout: scrub(outcome.stdout),
    stderr: scrub(outcome.stderr),
    staged: outcome.staged,
    files: Object.fromEntries(Object.entries(outcome.files).map(([name, text]) => [name, scrub(text)])),
    result: scrub(outcome.result),
    githubOutput: scrub(outcome.githubOutput),
  };
}

